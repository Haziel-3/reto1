package reto1;

public class Funciones1 {
	public static int suma(int num1, int num2) {
		
		return num1 + num2;
		
	}
	
	
	public static boolean esPar(int numero) {
		return numero % 2 == 0;
	}
	
	
	public static boolean esImpar(int numero) {
		return numero % 2 != 0;
	}


	

}
